#!/usr/bin/env python3
"""index.py : regenerate mcu/examples/README.md and mcu/templates/README.md from the toml files.

Run after adding or changing an example.toml / template.toml: python3 -I mcu/templates/tools/index.py
"""
import argparse
import os
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def collect(kind: str, fname: str) -> dict[str, list[tuple[str, dict]]]:
    """{sdk: [(name, parsed toml), ...]} for every <kind>/<sdk>/<name>/<fname>, sorted."""
    base = os.path.join(ROOT, kind)
    rows = {}
    if not os.path.isdir(base):
        return rows
    for sdk in sorted(os.listdir(base)):
        sd = os.path.join(base, sdk)
        if not os.path.isdir(sd) or sdk == "tools":
            continue
        for n in sorted(os.listdir(sd)):
            f = os.path.join(sd, n, fname)
            if os.path.isfile(f):
                with open(f, "rb") as fh:
                    rows.setdefault(sdk, []).append((n, tomllib.load(fh)))
    return rows


def esc(s) -> str:
    """Make a value safe for one markdown table cell."""
    return str(s).replace("|", "\\|").replace("\n", " ")


def write(kind: str, fname: str, title: str, intro: str, cols: list) -> None:
    """Write <kind>/README.md: one table per SDK; cols is [(header, fn(sdk, name, toml) -> cell)]."""
    rows = collect(kind, fname)
    out = [f"# {title}", "", "Generated by `mcu/templates/tools/index.py`; do not edit. Format: `mcu/templates/SPEC.md`.", "", intro, ""]
    total = 0
    for sdk, items in rows.items():
        out += [f"## {sdk}", "", "| " + " | ".join(c[0] for c in cols) + " |", "|" + "---|" * len(cols)]
        for n, m in items:
            cells = []
            for _, fn in cols:
                cells.append(esc(fn(sdk, n, m)))
            out.append("| " + " | ".join(cells) + " |")
            total += 1
        out.append("")
    if not rows:
        out.append("(none yet)")
    path = os.path.join(ROOT, kind, "README.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"index.py: {path}: {total} entries in {len(rows)} SDKs")


def j(m: dict, k: str) -> str:
    """A toml value as text (lists joined with commas)."""
    v = m.get(k, "")
    return ", ".join(v) if isinstance(v, list) else v


def main() -> None:
    argparse.ArgumentParser(description="Regenerate examples/README.md and templates/README.md from the toml files.").parse_args()
    write("examples", "example.toml", "Examples catalogue",
          "Complete buildable demos. Build all with `mcu/templates/tools/check.sh <sdk>`; outputs in `$BOX_OUT/30_39_tools/32_embedded/32_01_mcu/build/examples/<sdk>/<name>/<target>/`.",
          [("example", lambda s, n, m: f"[{n}]({s}/{n}/)"), ("targets", lambda s, n, m: j(m, "targets")),
           ("description", lambda s, n, m: j(m, "description")), ("hardware", lambda s, n, m: j(m, "hardware")),
           ("features", lambda s, n, m: j(m, "features")), ("status", lambda s, n, m: j(m, "status"))])
    write("templates", "template.toml", "Templates catalogue",
          "Project skeletons. `python3 -I mcu/templates/tools/instantiate.py <sdk> <template> <dest> --name N [--target T]` (refuses to overwrite).",
          [("template", lambda s, n, m: f"[{n}]({s}/{n}/)"), ("targets", lambda s, n, m: j(m, "targets")),
           ("default", lambda s, n, m: j(m, "default_target")), ("description", lambda s, n, m: j(m, "description"))])


if __name__ == "__main__":
    main()
