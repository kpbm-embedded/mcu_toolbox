# shellcheck shell=bash
# update-cmd.sh - the update, outdated, rollback and prune commands (dispatcher side).
#
# Pipeline per SDK:  plugin sdk_update (components -> installers, see update.sh)
#                    -> UPDATE_POST_CHECKS on the SDK and on sdks_to_recheck
#                    -> automatic rollback when anything fails, else keep the state + regenerate VERSIONS.md.
# Hooks for version management (later phase): sdks_to_recheck (reverse dependencies) and UPDATE_POST_CHECKS.

# Post-update checks, run in order; each takes <sdk> and returns non-zero to trigger the rollback.
UPDATE_POST_CHECKS=(update_check_rpath update_check_selfcheck update_check_libcheck)

# SDKs whose selfcheck must pass after <sdk> changed. Today: the SDK itself.
# Hook: return the reverse dependencies too once component manifests exist (mcu rdeps).
sdks_to_recheck() {
  local sdk="$1"
  printf '%s\n' "$sdk"
}

# Post-check: add $ORIGIN RUNPATHs to new binaries of the SDK (never fails the update).
update_check_rpath() {
  local sdk="$1"
  echo "[post] patch-rpath $sdk"
  (
    # shellcheck source=/dev/null
    source "$MCU_ROOT/host/env.sh"
    "$MCU_ROOT/host/patch-rpath.sh" "$MCU_ROOT/$sdk"
  ) 2>&1 | tail -5 | sed 's/^/  /'
  return 0
}

# Post-check: strict-PATH selfcheck of the SDK and of everything that depends on it.
update_check_selfcheck() {
  local sdk="$1" other rc=0
  sysbin_refresh
  for other in $(sdks_to_recheck "$sdk"); do
    echo "[post] selfcheck $other"
    selfcheck_one "$other" || rc=1
  done
  return "$rc"
}

# Post-check: no host binary of the SDK may load libraries from the OS.
update_check_libcheck() {
  local sdk="$1" rc=0
  echo "[post] libcheck $sdk"
  set +e
  libcheck_run "$MCU_ROOT/$sdk" | tail -3 | sed 's/^/  /'
  rc="${PIPESTATUS[0]}"
  set -e
  return "$rc"
}

# Run every UPDATE_POST_CHECKS step; stops at the first failure.
update_run_post_checks() {
  local sdk="$1" check
  for check in "${UPDATE_POST_CHECKS[@]}"; do
    "$check" "$sdk" || return 1
  done
}

# Rewrite <sdk>/VERSIONS.md from sdk_versions (atomically) and make sure the README links to it.
update_write_versions() {
  local sdk="$1" dir="$MCU_ROOT/$1"
  # shellcheck disable=SC2016  # literal backticks (markdown)
  {
    printf '# %s versions\n\nGenerated by `mcu update %s` on %s (do not edit).\n\n```\n' "$sdk" "$sdk" "$(date +%F)"
    plugin_call "$sdk" sdk_versions 2>&1 || true
    printf '```\n'
  } | write_atomic "$dir/VERSIONS.md"
  if [[ -f "$dir/README.md" ]] && ! grep -q 'VERSIONS.md' "$dir/README.md"; then
    # shellcheck disable=SC2016  # literal backticks (markdown)
    printf '\nInstalled versions (generated by `mcu update`): see [VERSIONS.md](VERSIONS.md).\n' >>"$dir/README.md"
  fi
}

# Replay the recorded state file of <sdk> in reverse (plugin sdk_rollback, default in update.sh).
update_rollback_state() {
  local sdk="$1" file="$2"
  UPD_FILE="$file" plugin_call "$sdk" sdk_rollback
}

# Relabel this SDK's "updated" rows as "rolled-back" in the results file.
update_mark_rolled_back() {
  local sdk="$1" tmp="$MCU_RESULTS.tmp"
  awk -F'\t' -v OFS='\t' -v s="$sdk" '$1 == s && $5 == "updated" {$5 = "rolled-back"} {print}' "$MCU_RESULTS" >"$tmp"
  mv "$tmp" "$MCU_RESULTS"
}

# Number of result rows of <sdk> with status <status>.
update_count_rows() {
  local sdk="$1" status="$2"
  awk -F'\t' -v s="$sdk" -v st="$status" '$1 == s && $5 == st' "$MCU_RESULTS" | wc -l
}

# Cache "newer/unknown component counts" of the last check for `mcu status`.
update_record_check() {
  local sdk="$1"
  printf '%s\t%s\t%s\n' "$(date +%s)" "$(update_count_rows "$sdk" newer)" "$(update_count_rows "$sdk" unknown)" \
    | write_atomic "$(state_dir "$sdk")/update-check"
}

# Undo a failed update and relabel its rows.
update_abort() {
  local sdk="$1" state="$2"
  if [[ -s "$state" ]]; then
    echo "--- rolling back $sdk"
    update_rollback_state "$sdk" "$state" || log_error "rollback of $sdk reported errors"
  fi
  update_mark_rolled_back "$sdk"
}

# Keep the applied state as <sdk>/.update-state (older ones get a timestamp suffix).
update_keep_state() {
  local sdk="$1" state="$2" kept="$MCU_ROOT/$1/.update-state"
  [[ -s "$state" ]] || return 0
  [[ -e "$kept" ]] && mv "$kept" "$kept.$(date +%Y%m%d-%H%M%S)"
  cp "$state" "$kept"
}

# One SDK: plugin update, then post-checks; any failure rolls back. Rows go to $MCU_RESULTS.
update_one() {
  local sdk="$1" state rc=0 changed
  shift
  require_sdk "$sdk"
  state="$MCU_OUT_BASE/_update/$sdk.state"
  mkdir -p "$MCU_OUT_BASE/_update"
  : >"$state"
  export UPD_STATE="$state"
  set +e
  plugin_call "$sdk" sdk_update "$@"
  rc=$?
  set -e
  unset UPD_STATE
  update_record_check "$sdk"
  if ((rc != 0)); then
    log_error "$sdk: update failed (rc=$rc)"
    update_abort "$sdk" "$state"
    return 1
  fi
  changed="$(update_count_rows "$sdk" updated)"
  is_yes && ((changed > 0)) || return 0
  echo "--- post-update checks for $sdk"
  if ! update_run_post_checks "$sdk"; then
    log_error "$sdk: post-update check failed -> automatic rollback"
    update_abort "$sdk" "$state"
    return 1
  fi
  update_keep_state "$sdk" "$state"
  update_write_versions "$sdk"
  echo "OK $sdk updated; state in $sdk/.update-state ('mcu rollback $sdk' undoes it), versions in $sdk/VERSIONS.md"
}

# Print the results file as a table: sdk, component, old -> new, result. Optional filter: only non-current rows.
update_summary() {
  local only_changes="${1:-0}"
  [[ -s "$MCU_RESULTS" ]] || return 0
  awk -F'\t' -v only="$only_changes" '
    { key = $1 FS $2; if (!(key in result)) order[++n] = key
      sdk[key] = $1; comp[key] = $2; old[key] = $3; new[key] = $4; result[key] = $5 }
    END {
      print "SDK\tCOMPONENT\tOLD -> NEW\tRESULT"
      for (i = 1; i <= n; i++) {
        k = order[i]; r = result[k]
        if (only == 1 && r == "current") continue
        if (r == "newer") r = "available (dry run)"
        print sdk[k] "\t" comp[k] "\t" (old[k] == new[k] ? old[k] : old[k] " -> " new[k]) "\t" r
      }
    }' "$MCU_RESULTS" | print_table
}

# Start a results file for this run (exported for plugin upd_log).
update_results_begin() {
  mkdir -p "$MCU_OUT_BASE/_update"
  export MCU_RESULTS="$MCU_OUT_BASE/_update/results.$$"
  : >"$MCU_RESULTS"
}

# update <sdk|all> [version]: dry run by default; --yes applies, verifies and rolls back on failure.
cmd_update() {
  local which="${1:-}" sdk rc=0
  [[ -n "$which" ]] || die_usage update "need <sdk|all>"
  shift
  [[ "$which" == all && $# -gt 0 ]] && die_usage update "a version only makes sense for one sdk"
  update_results_begin
  for sdk in $(sdk_selection "$which"); do
    printf '=== %s\n' "$sdk"
    update_one "$sdk" "$@" || {
      log_error "$sdk failed, continuing"
      rc=1
    }
  done
  echo
  echo "=== update summary"
  update_summary 0
  grep -qP '\t(failed|rolled-back)$' "$MCU_RESULTS" && rc=1
  return "$rc"
}

# outdated: dry-run update of every SDK, printing only the components that are not current.
cmd_outdated() {
  local sdk log current
  [[ $# -eq 0 ]] || die_usage outdated "takes no arguments"
  update_results_begin
  log="$MCU_OUT_BASE/_update/outdated.log"
  : >"$log"
  for sdk in $(sdk_names); do
    plugin_has "$sdk" sdk_update || continue
    log_info "checking $sdk"
    MCU_YES=0 MCU_DRY_RUN=1 update_one "$sdk" >>"$log" 2>&1 || log_warn "$sdk: check failed (see $log)"
  done
  update_summary 1
  current="$(awk -F'\t' '$5 == "current"' "$MCU_RESULTS" | wc -l)"
  printf '\n%s components current; full output: %s\n' "$current" "$log"
}

# rollback <sdk>: undo the last applied update from <sdk>/.update-state.
cmd_rollback() {
  local sdk="${1:-}" state
  [[ $# -eq 1 ]] || die_usage rollback "need one <sdk>"
  require_sdk "$sdk"
  state="$MCU_ROOT/$sdk/.update-state"
  [[ -s "$state" ]] || die "$sdk: no recorded state (.update-state); nothing to roll back"
  if is_dry_run; then
    echo "would replay $state in reverse:"
    tac "$state"
    return 0
  fi
  update_rollback_state "$sdk" "$state" || die "$sdk: rollback reported errors"
  mv "$state" "$state.rolledback-$(date +%Y%m%d-%H%M%S)"
  update_write_versions "$sdk"
  echo "rolled back $sdk; versions:"
  plugin_call "$sdk" sdk_versions | head -20
}

# prune [sdk|all]: list (with --yes: trash) versioned dirs older than the previous version.
cmd_prune() {
  [[ $# -le 1 ]] || die_usage prune "too many arguments"
  [[ "${1:-all}" == all ]] || require_sdk "$1"
  each_sdk_call sdk_prune "${1:-all}"
}

# setup [cmd] [sel...]: install/check the pinned components of config/pins.tsv (tool/setup.sh); -n is passed as --dry-run.
cmd_setup() {
  local args=("$@")
  [[ "${MCU_DRY_RUN:-0}" == 1 ]] && args+=(--dry-run)
  bash "$MCU_ROOT/setup.sh" "${args[@]}"
}
